/**
 * Regenerates src/bank-codes.ts from the ČNB CSV.
 * Usage: node scripts/generate-bank-codes.ts [path-to-csv]   (downloads when no path is given)
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const URL_CSV =
  'https://www.cnb.cz/cs/platebni-styk/.galleries/ucty_kody_bank/download/kody_bank_CR.csv'

export function parseBankCsv(text: string): { code: string; name: string; bic: string | null }[] {
  const rows = text.replace(/^﻿/, '').split(/\r?\n/).slice(1)
  const out: { code: string; name: string; bic: string | null }[] = []
  for (const row of rows) {
    if (!row.trim()) continue
    const [code, name, bic] = row.split(';').map((c) => c.trim())
    if (!code || !/^\d{4}$/.test(code) || !name) continue
    out.push({ code, name, bic: bic ? bic : null })
  }
  return out.sort((a, b) => a.code.localeCompare(b.code))
}

export function renderBankCodes(banks: ReturnType<typeof parseBankCsv>, date: string): string {
  const lines = banks.map(
    (b) => `  { code: '${b.code}', name: ${JSON.stringify(b.name)}, bic: ${b.bic ? `'${b.bic}'` : 'null'} },`,
  )
  return `// GENERATED by scripts/generate-bank-codes.ts from the ČNB list of payment system codes (${date}). Do not edit.
export interface BankCode {
  code: string
  name: string
  bic: string | null
}

export const BANK_CODES: readonly BankCode[] = [
${lines.join('\n')}
]

const BY_CODE = new Map(BANK_CODES.map((b) => [b.code, b]))

export function findBank(code: string): BankCode | undefined {
  return BY_CODE.get(code)
}

export function isKnownBankCode(code: string): boolean {
  return BY_CODE.has(code)
}
`
}

async function main() {
  const arg = process.argv[2]
  const text = arg ? await readFile(arg, 'utf8') : await (await fetch(URL_CSV)).text()
  const banks = parseBankCsv(text)
  if (banks.length < 20) throw new Error(`Suspiciously few banks parsed: ${banks.length}`)
  const out = fileURLToPath(new URL('../src/bank-codes.ts', import.meta.url))
  await writeFile(out, renderBankCodes(banks, new Date().toISOString().slice(0, 10)))
  console.log(`Wrote ${banks.length} banks to ${out}`)
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) await main()
